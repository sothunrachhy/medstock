export function medicineDocs() {
  const injections = INJECTIONS.map(([name, form, strength, demo, category], i) => ({
    name,
    form,
    strength,
    category: category || 'INJECTION',
    order: i + 1,
    minStock: category === 'NARCOTIC' ? 5 : 10,
    demo,
  }));
  const pills = PILLS.map((name, i) => ({
    name,
    form: 'គ្រាប់',
    strength: '',
    category: 'PILL',
    order: i + 1,
    minStock: 20,
    demo: 100 + ((i * 37) % 400),
  }));
  return [...injections, ...pills];
}
